//Exercicio - Carro x Salario

void main() {
  var salario = 5000;
  var contas = 5000;

  var carro1 = "Fusca";
  var carro2 = "Brasilia";

  if (salario > contas) {
    print("Ufa que bom");
  } else {
    print("Que pena");
  }

  if (salario == contas) {
    print("Igual");
  } else {
    print("Diferente");
  }

  if (carro1 == carro2) {
    print("Strings iguais");
  } else {
    print("Strings diferentes");
  }
}
