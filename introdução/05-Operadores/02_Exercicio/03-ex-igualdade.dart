// Operadores relacionais de comparação 

void main()  {

  //Dois valores para comparar entre si 
  final int valor1 = 5;  
  final int valor2  = 10;

  // == verifica igualdadade !=verifica a diferança ou desigualdade 
  print('valor 1 == valor 2: ${valor1 == valor2}'); //false 
  print('valor 1 =! valor 2: ${valor1 != valor2}'); //true

  print('valor 1 > valor 2:  ${valor1 > valor2}');  //false 
  print('valor 1 < valor 2:  ${valor1 < valor2}'); //true

}

