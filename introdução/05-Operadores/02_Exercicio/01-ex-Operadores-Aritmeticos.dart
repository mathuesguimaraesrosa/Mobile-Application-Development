// Ex Cria um programa que demonstra cinco operadores. 

void main() {
  
  final int a = 22; //variável a = 10
  final int b = 16; //variával b  = 5

  print('Soma: ${a + b}'); // Operador adição ou de somar. 
  print('Subtração: ${a - b}'); // Operador de subtração. 
  print('Multiplicação: ${a * b}'); // Operador de multiplicar. 
  print('Divisão: ${a / b}'); // Operador de divisão.
  print('Resto da divisão: ${a % b}'); // Operador de resto da divisão.
}