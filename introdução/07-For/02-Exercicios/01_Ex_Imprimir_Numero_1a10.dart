//Exercicio imprimir os numeros inteiros de 1 a 10 utilziando o laço 'for'
// O for é ideal quando o numero de interações é conhecido com antecedência

void main() {
  //Laço de 1 até 10 incremento unitário. 
  for (int i = 1; i <=10; i++) {
    //Exibindo o valor atual do contador 
    print(i);
  }
}